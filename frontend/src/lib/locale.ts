type UiText = typeof ui | typeof enhancedEnglishUi;

const languageContext = createContext<{
  language: UiLanguage;
  setLanguage: (language: UiLanguage) => void;
  text: UiText;
}>({ language: 'vi', setLanguage: () => undefined, text: ui });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<UiLanguage>(() => {
    const saved = localStorage.getItem('wikibooklm-language');
    return saved === 'en' ? 'en' : 'vi';
  });
  const setLanguage = (next: UiLanguage) => {
    localStorage.setItem('wikibooklm-language', next);
    setLanguageState(next);
  };
  return createElement(
    languageContext.Provider,
    { value: { language, setLanguage, text: language === 'en' ? enhancedEnglishUi : ui } },
    children,
  );
}

export function useUi() {
  return useContext(languageContext);
}
